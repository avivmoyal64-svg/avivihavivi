 o=o.replace(/\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sept|Sep|Oct|Nov|Dec)\b\s+(\d{1,2})\b/g,function(m,mo,dd){return dd+" "+MON[mo].replace(/^ב/,"ב")});
